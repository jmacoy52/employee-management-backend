const express = require('express');
const router = express.Router();
const UserController = require('../controllers/userController');
const { authenticateToken, optionalAuth, authorizeAdmin, authorizeHR } = require('../middleware/authMiddleware');
const { authLimiter } = require('../config/rateLimits');
const userValidation = require('../validator/userValidator');
const { validationResult } = require('express-validator');

// Middleware to handle validation errors
const handleValidation = (req, res, next) => {
  const errors = validationResult(req);
  if (!errors.isEmpty()) {
    return res.status(400).json({ errors: errors.array() });
  }
  next();
};

// Route to register a user in the caller's organisation (admin: any role; HR: employee accounts).
// Kept at this path for the frontend; anonymous self-sign-up is closed (403 SELF_SIGNUP_CLOSED).
router.post('/register', authLimiter, optionalAuth, UserController.requireAccountCreator, userValidation, handleValidation, UserController.register);

// Route to login a user (Public)
router.post('/login', authLimiter, UserController.login);

// Reset a password with a one-time link generated by an admin (Public)
router.post('/reset-password', authLimiter, UserController.resetPasswordWithToken);

// Sign out (revokes every token of this account) and change own password (Authenticated users)
router.post('/logout', authenticateToken, UserController.logout);
router.put('/change-password', authenticateToken, UserController.changePassword);

// Current account and its linked employee record (Authenticated users)
router.get('/me', authenticateToken, UserController.me);
router.get('/me/employee', authenticateToken, UserController.myEmployeeRecord);

// Users that can be linked to an employee record (HR/Admin)
router.get('/linkable', authenticateToken, authorizeHR, UserController.linkableUsers);

// Route to get all users (Admin only)
router.get('/all', authenticateToken, authorizeAdmin, UserController.getAllUsers);

// Route to update user role (Admin only)
router.put('/:id/role', authenticateToken, authorizeAdmin, UserController.updateUserRole);

// Route to activate/deactivate a user (Admin only)
router.put('/:id/status', authenticateToken, authorizeAdmin, UserController.setUserStatus);

// Password reset by an admin: temporary password, or a one-time reset link (Admin only)
router.post('/:id/temporary-password', authenticateToken, authorizeAdmin, UserController.setTemporaryPassword);
router.post('/:id/reset-link', authenticateToken, authorizeAdmin, UserController.createResetLink);

// Route to delete a user (Admin only)
router.delete('/:id', authenticateToken, authorizeAdmin, UserController.deleteUser);

// Route to get user profile (Authenticated users)
router.get('/profile', authenticateToken, UserController.getProfile);

// Route to update user profile (Authenticated users)
router.put('/profile', authenticateToken, UserController.updateProfile);

module.exports = router;
